"""Real (non-stub) local Nextflow runs on committed test data (-profile test_snv / test_sv).

Requires nextflow and the pipeline's Python deps on PATH (e.g. the conda env); the SV run also
needs the svtyper fork (installed, or SVTYPER_SRC). Expected values come from
tests/data/synthetic/truth.json (generated by tests/make_fixtures.py)."""
import json
import os
import shutil
import subprocess

import pandas as pd
import pytest

import svtyper_helpers as sh

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYN = os.path.join(REPO, "tests", "data", "synthetic")
pytestmark = pytest.mark.skipif(shutil.which("nextflow") is None, reason="nextflow not on PATH")


def _run(entry, profile, tmp_path, *extra):
    env = sh.svtyper_env()
    env.setdefault("NXF_HOME", str(tmp_path / "nxf_home"))
    env["NXF_OFFLINE"] = "true"
    env["NXF_ANSI_LOG"] = "false"
    out = tmp_path / "out"
    cmd = ["nextflow", "run", os.path.join(REPO, entry), "-profile", profile, "-work-dir", str(tmp_path / "work"),
           "--outdir", str(out), *extra]
    res = subprocess.run(cmd, cwd=str(tmp_path), env=env, capture_output=True, text=True, timeout=900)
    assert res.returncode == 0, res.stdout[-4000:] + res.stderr[-4000:]
    return out


def test_snv_profile_reproduces_synthetic_truth(tmp_path):
    truth = json.load(open(os.path.join(SYN, "truth.json")))
    out = _run("snv_genotyping.nf", "test_snv", tmp_path)
    df = pd.read_csv(out / "T1_snv_genotyping.csv.gz", dtype={"chromosome": str})
    assert len(df) == 4
    s1 = df[(df.chromosome == "1") & (df.position == truth["S1"][1])].iloc[0]
    t = truth["truth_S1"]
    assert (s1.ref_count, s1.alt_count, s1.other_count) == (t["ref_count"], t["alt_count"], t["other_count"])
    assert s1.callers == "caveman;mutect" and bool(s1.called_in_target)
    qc = json.load(open(out / "T1_genotyping_qc.json"))
    assert qc["chunks"] == 2 and qc["conflict_fragments"] == t["conflict_count"]
    assert (out / "union" / "T1_union_snvs.vcf.gz.tbi").exists()
    assert (out / "inputs").is_dir()


@pytest.mark.skipif(not sh.available(), reason="svtyper fork not importable (set SVTYPER_SRC)")
def test_sv_profile_genotypes_na12878_union(tmp_path):
    out = _run("sv_genotyping.nf", "test_sv", tmp_path, "--svtyper_cmd", sh.svtyper_cmd())
    df = pd.read_csv(out / "NA12878_sv_genotyping.csv.gz", dtype={"chromosome_1": str})
    assert len(df) == 6
    qc = json.load(open(out / "NA12878_genotyping_qc.json"))
    assert qc["positive_control_fraction"] == 1.0 and qc["chunks"] == 2
    assert (df[~df.called_in_target].alt_fragments == 0).all()
    assert (out / "NA12878.lib_info.json").exists() and (out / "NA12878_svtyper.vcf.gz").exists()
